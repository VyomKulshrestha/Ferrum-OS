#!/usr/bin/env python3
"""Build tools/ol1_kaggle/ol1_kaggle.py: scripts/ol1_core.py followed by runner.py, one self-contained file
to paste into a Kaggle notebook. test_ol1_kaggle checks that the built file is up to date.

    python tools/ol1_kaggle/build.py
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = HERE / "ol1_kaggle.py"


def build() -> str:
    core = (ROOT / "scripts/ol1_core.py").read_text(encoding="utf-8")
    runner = (HERE / "runner.py").read_text(encoding="utf-8")
    digest = hashlib.sha256(json.dumps(core, sort_keys=True).encode()).hexdigest()[:16]
    head = (
        "# ol1 Kaggle script: generated by tools/ol1_kaggle/build.py from scripts/ol1_core.py and\n"
        "# tools/ol1_kaggle/runner.py. Do not edit; edit the sources and rebuild.\n"
    )
    core = core.replace("#!/usr/bin/env python3\n", "", 1)
    runner = runner.replace("# ruff: noqa: F821", "# (names from ol1_core above)")
    core = core.replace(
        'if __name__ == "__main__":',
        "if False:  # core main disabled in the Kaggle build",
    )
    return head + core + f'\n\nCORE_DIGEST = "{digest}"\n\n' + runner


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    print("written", OUT)
