def spec_for(domain: str, history: int):
    return dataclasses.replace(v2data.spec_for(domain), history=history)


def windows(rows: list[dict], spec, complete: bool = False) -> Windows:
    """Identical eligibility, targets and masks to v2, with spec.history causal steps."""
    grouped: dict[str, list[dict]] = {}
    for row in rows:
        grouped.setdefault(row["episode"], []).append(row)
    result = [[] for _ in range(7)]
    for episode, sequence in sorted(grouped.items()):
        sequence.sort(key=lambda row: row["step"])
        if len({row["step"] for row in sequence}) != len(sequence):
            raise ValueError(f"duplicate step in {episode}")
        for index, row in enumerate(sequence):
            future = sequence[index:index + HORIZON]
            for k, item in enumerate(future):
                if item["step"] != row["step"] + k:
                    future = future[:k]
                    break
            if complete and len(future) != HORIZON:
                continue
            history = sequence[max(0, index - spec.history + 1):index + 1]
            while len(history) > 1 and history[0]["step"] != row["step"] - len(history) + 1:
                history = history[1:]
            pad = spec.history - len(history)
            states = [history[0]["state"]] * pad + [item["state"] for item in history]
            actions = [np.zeros(spec.action_size, np.float32)] * pad + [item["action"] for item in history]
            actual = [item["next_state"] for item in future]
            planned = [item["action"] for item in future]
            valid = [1.0] * len(future) + [0.0] * (HORIZON - len(future))
            actual += [actual[-1]] * (HORIZON - len(actual))
            planned += [planned[-1]] * (HORIZON - len(planned))
            for output, value in zip(result, (states, actions, planned, actual, valid, episode, row["source"])):
                output.append(value)
    if not result[0]:
        raise ValueError("no eligible causal windows")
    return Windows(*[np.asarray(value, dtype=np.float32 if i < 5 else str) for i, value in enumerate(result)])


def history_mask(data: Windows) -> np.ndarray:
    """1 where a history slot holds a real observation, 0 for left padding (causal)."""
    # Padding repeats the first state with a zero action; the most recent slot is always real.
    real_action = np.abs(data.actions).sum(-1) > 0
    mask = np.zeros(real_action.shape, np.float32)
    mask[:, -1] = 1
    for j in range(real_action.shape[1] - 2, -1, -1):
        mask[:, j] = np.where(real_action[:, j], mask[:, j + 1], 0)
    return mask


