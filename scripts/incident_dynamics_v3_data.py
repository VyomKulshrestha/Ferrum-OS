def legacy_rows(domain: str) -> dict:
    """Original development partitions (cached); never final rows."""
    path = WORK / f"legacy-{domain}.pkl"
    if path.exists():
        return pickle.loads(path.read_bytes())
    protocol = architecture.load_json(architecture.PROTOCOL)
    guard = architecture.install_final_guard(protocol)
    loader = architecture.os_development if domain == "ferrumos" else architecture.physical_development
    _, train, validation, metadata = loader(protocol)
    if guard["attempted"]:
        raise AssertionError("final access during development load")
    value = {"train": train, "validation": validation, "metadata": metadata}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(pickle.dumps(value))
    return value


def save(path: Path, data: Windows) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(path, **vars(data))


def load(path: Path) -> Windows:
    return v2data.load_windows(path)


def concat(*parts: Windows) -> Windows:
    return Windows(**{key: np.concatenate([getattr(p, key) for p in parts]) for key in Windows.__dataclass_fields__})
