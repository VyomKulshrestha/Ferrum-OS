def _rng(*parts) -> np.random.Generator:
    digest = hashlib.sha256(":".join(str(p) for p in parts).encode()).digest()
    return np.random.default_rng(int.from_bytes(digest[:8], "little"))


def _os_action(rng, spec):
    name = str(rng.choice(OS_ACTIONS, p=OS_ACTION_P))
    action = temporal.action_record(name)
    vector = legacy.standardize_action(action["id"], [0.0] * os_model.ACTION_FEATURE_SIZE, spec.action_size, os_model.NUM_TOOLS)
    return action, vector


def os_episode(mechanism: str, rng, spec, steps: int, strength: float = 1.0):
    """Yield (observed_state, action_vector, next_true_state) for one episode."""
    state = np.zeros(48, np.float32)
    state[[0, 1, 3]] = rng.uniform(0.3, 0.9, 3)
    state[2] = rng.uniform(0, 0.7)
    base = np.zeros(48, np.float32)
    base[[0, 1, 3]] = rng.uniform(-0.002, 0.006, 3)
    s = float(strength)
    p = {}
    if mechanism == "constant_pressure":
        base[[0, 1, 3]] = rng.uniform(-0.002, 0.012, 3) * s
    elif mechanism == "accelerating_leak":
        p["accel"] = rng.uniform(0.0004, 0.0018) * s
        p["disk"] = rng.random() < .5
    elif mechanism == "exponential_amplification":
        p["seed"], p["growth"] = rng.uniform(0.001, 0.004), 1 + rng.uniform(0.12, 0.35) * s
    elif mechanism == "sudden_step":
        p["at"], p["dim"], p["jump"] = int(rng.integers(3, steps - 2)), int(rng.choice([0, 1])), rng.uniform(0.04, 0.16) * s
    elif mechanism == "retry_oscillation":
        p["period"], p["amp"], p["phase"] = int(rng.integers(3, 7)), rng.uniform(0.006, 0.02) * s, rng.uniform(0, 2 * np.pi)
    elif mechanism == "coupled_cascade":
        p["proc"], p["couple"], p["disk"] = rng.uniform(0.004, 0.012) * s, rng.uniform(0.3, 0.9), rng.uniform(0.1, 0.5)
    elif mechanism == "crash_restart":
        p["leak"], p["cap"], p["recover"] = rng.uniform(0.006, 0.016) * s, rng.uniform(0.9, 1.0), rng.uniform(0.01, 0.03)
    elif mechanism == "log_storm":
        p["files"], p["disk"] = rng.uniform(0.004, 0.02) * s, rng.uniform(0.004, 0.014) * s
    elif mechanism == "frozen_telemetry":
        base[[0, 1, 3]] = rng.uniform(0.0, 0.01, 3) * s
        p["dim"], p["start"], p["length"] = int(rng.choice([0, 1, 3])), int(rng.integers(2, steps - 3)), int(rng.integers(2, 5))
    elif mechanism == "regime_shift":
        base[[0, 1, 3]] = rng.uniform(-0.002, 0.012, 3) * s
        p["at"], p["factor"] = int(rng.integers(4, steps - 1)), float(rng.choice([-1.0, -0.5, 0.0, 1.5, 2.0]))
    else:
        raise KeyError(mechanism)
    phase_load = 0.0
    frozen_value = None
    for step in range(steps):
        action, vector = _os_action(rng, spec)
        exo = base.copy()
        if mechanism == "accelerating_leak":
            exo[1] += p["accel"] * step
            if p["disk"]:
                exo[3] += 0.5 * p["accel"] * step
        elif mechanism == "exponential_amplification":
            exo[0] += p["seed"] * p["growth"] ** step
            exo[1] += 0.4 * p["seed"] * p["growth"] ** step
        elif mechanism == "sudden_step" and step == p["at"]:
            exo[p["dim"]] += p["jump"]
        elif mechanism == "retry_oscillation":
            load = p["amp"] * np.sin(2 * np.pi * step / p["period"] + p["phase"])
            exo[0] += load
            exo[1] += 0.6 * load
        elif mechanism == "coupled_cascade":
            exo[0] += p["proc"]
            exo[1] += p["couple"] * max(0.0, state[0] - 0.5) * 0.05
            exo[3] += p["disk"] * max(0.0, state[1] - 0.6) * 0.05
        elif mechanism == "crash_restart":
            if state[1] >= p["cap"]:
                exo[1] -= 0.45
                exo[0] -= 0.25
                phase_load = p["recover"]
            else:
                exo[1] += p["leak"]
                exo[0] += phase_load
        elif mechanism == "log_storm":
            exo[2] += p["files"]
            exo[3] += p["disk"]
        elif mechanism == "regime_shift" and step >= p["at"]:
            exo[[0, 1, 3]] *= p["factor"]
        nxt = temporal.apply_os(state, action, exo)
        observed = state.copy()
        if mechanism == "frozen_telemetry":
            if step == p["start"]:
                frozen_value = state[p["dim"]]
            if p["start"] <= step < p["start"] + p["length"] and frozen_value is not None:
                observed[p["dim"]] = frozen_value
        yield observed, vector, nxt
        state = nxt


def _move_features(rng):
    f = physical.action_features(rng, physical.MOVE)
    f[:2] *= .3
    return f


def physical_episode(mechanism: str, rng, spec, steps: int, strength: float = 1.0):
    state = physical.initial_state(rng)
    state[physical.HUMANS] = 0
    state[physical.ESTOP] = 0
    state[physical.ONLINE] = 1
    state[physical.CLEARANCE] = rng.uniform(0.3, 0.95)
    state[physical.BATTERY] = rng.uniform(0.1, 0.8)
    state[physical.LINK] = rng.uniform(0.15, 0.9)
    drift = np.zeros(16, np.float32)
    s = float(strength)
    p = {}
    if mechanism in ("constant_pressure", "regime_shift"):
        drift[physical.LINK] = -rng.uniform(0, 0.018) * s
        drift[physical.BATTERY] = -rng.uniform(0, 0.008) * s
        if mechanism == "regime_shift":
            p["at"], p["factor"] = int(rng.integers(4, steps - 1)), float(rng.choice([0.0, 0.5, 1.5, 2.5]))
    elif mechanism == "accelerating_drain":
        p["accel"] = rng.uniform(0.0004, 0.0016) * s
    elif mechanism == "link_jamming":
        p["prob"], p["depth"], p["recover"] = rng.uniform(0.1, 0.3), rng.uniform(0.04, 0.14) * s, rng.uniform(0.4, 0.8)
    elif mechanism == "actuator_gain_fault":
        p["gain"] = float(rng.choice([0.5, 0.7, 1.4, 1.8]))
    elif mechanism == "approaching_obstacle":
        p["rate"] = rng.uniform(0.01, 0.04) * s
    elif mechanism == "replayed_sensors":
        p["start"], p["length"] = int(rng.integers(3, steps - 4)), int(rng.integers(2, 5))
    elif mechanism == "position_bias":
        p["bias"] = rng.uniform(-0.03, 0.03, 2) * s
    elif mechanism == "vibration_degradation":
        p["rate"] = rng.uniform(0.01, 0.04) * s
    elif mechanism == "stale_observation":
        p["period"] = int(rng.integers(3, 6))
    else:
        raise KeyError(mechanism)
    jam = 0.0
    history = []
    previous_observed = state.copy()
    for step in range(steps):
        action_id = int(rng.choice([physical.MOVE, physical.INSPECT, physical.DIAGNOSE, physical.STOP], p=[.55, .15, .15, .15]))
        features = _move_features(rng) if action_id == physical.MOVE else physical.action_features(rng, action_id)
        vector = legacy.standardize_action(action_id, features, spec.action_size, physical.ACTION_COUNT)
        applied = features.copy()
        if mechanism == "actuator_gain_fault" and action_id == physical.MOVE:
            applied[:2] = np.clip(applied[:2] * p["gain"], -1, 1)
        nxt = physical.transition(state, action_id, applied, rng)
        exo = drift.copy()
        if mechanism == "regime_shift" and step >= p["at"]:
            exo *= p["factor"]
        elif mechanism == "accelerating_drain":
            exo[physical.BATTERY] -= p["accel"] * step
        elif mechanism == "link_jamming":
            if rng.random() < p["prob"]:
                jam = p["depth"]
            exo[physical.LINK] -= jam
            jam *= 1 - p["recover"]
        elif mechanism == "approaching_obstacle":
            exo[physical.CLEARANCE] -= p["rate"]
        elif mechanism == "vibration_degradation":
            exo[physical.VIBRATION] += p["rate"]
            exo[physical.HEALTH] -= 0.6 * p["rate"]
        nxt += exo
        nxt[2:] = np.clip(nxt[2:], 0, 1)
        nxt[physical.MARGIN] = np.clip(1 - max(abs(nxt[0]), abs(nxt[1])), -.25, 1)
        if mechanism == "vibration_degradation" and nxt[physical.VIBRATION] > 0.62:
            nxt[physical.FAULT] = 1
        observed = state.copy()
        history.append(state.copy())
        if mechanism == "replayed_sensors" and p["start"] <= step < p["start"] + p["length"]:
            source = history[max(0, step - p["length"] - 1)]
            observed[[physical.X, physical.Y, physical.CLEARANCE]] = source[[physical.X, physical.Y, physical.CLEARANCE]]
        elif mechanism == "position_bias":
            observed[[physical.X, physical.Y]] += p["bias"] * step
        elif mechanism == "stale_observation" and step % p["period"] == p["period"] - 1:
            observed[[physical.X, physical.Y, physical.CLEARANCE]] = previous_observed[[physical.X, physical.Y, physical.CLEARANCE]]
        yield observed, vector, nxt
        previous_observed = observed
        state = nxt


def mechanism_rows(domain: str, partition: str, mechanisms: list[str], episodes: int, seed: int,
                   steps: int = 14, strength_range=(0.6, 1.4), sources: dict | None = None) -> list[dict]:
    spec = spec_for(domain, 3)
    if partition != "final" and set(mechanisms) & set(HELD_OUT_MECHANISMS[domain]):
        raise PermissionError("held-out mechanisms are generated only for the registered final catalog")
    output = []
    for episode in range(episodes):
        mechanism = mechanisms[episode % len(mechanisms)]
        rng = _rng("v3", domain, partition, seed, episode)
        strength = float(rng.uniform(*strength_range))
        generator = os_episode if domain == "ferrumos" else physical_episode
        source = (sources or {}).get(mechanism, mechanism)
        for step, (observed, vector, nxt) in enumerate(generator(mechanism, rng, spec, steps, strength)):
            output.append({"episode": f"v3:{domain}:{partition}:{seed}:{episode}", "step": step,
                           "state": observed.astype(np.float32), "action": np.asarray(vector, np.float32),
                           "next_state": nxt.astype(np.float32), "source": source,
                           "hazard": mechanism, "dangerous": False})
    return output


