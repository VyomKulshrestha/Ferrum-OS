#!/usr/bin/env python3
"""Build the named preprint version of "Thresholds That Travel" from the anonymous ACM source.

    python scripts/tt1_named_version.py

Reads docs/research/paper/tt1_paper_pack/latex/{main.tex,refs.bib} and writes latex_named/ beside it, with
the author block, the public repository instead of the anonymous artifact copy, the citation of the
author's earlier registered studies instead of "[anonymized]", no review line numbers, no venue header and
no generative-AI section (the conference copies keep it).
Every replacement must match exactly once, so a change to the anonymous source that breaks one stops the
build instead of producing a half-named paper.
"""
from __future__ import annotations

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACK = ROOT / "docs/research/paper/tt1_paper_pack"
SRC, DST = PACK / "latex", PACK / "latex_named"
REPO = "https://github.com/VyomKulshrestha/Ferrum-OS"
ANON = "https://anonymous.4open.science/r/thresholds-that-travel-artifact-579B/"

REPLACE = [
    ("%% Thresholds That Travel -- anonymous submission, ACM ASIA CCS 2027 (sigconf).",
     "%% Thresholds That Travel -- named preprint (generated by scripts/tt1_named_version.py from\n"
     "%% latex/main.tex, the anonymous ACM ASIA CCS 2027 submission; edit that file, not this one)."),
    ("%% Anonymization: author block, ORCID, repository links and the authors' own artifact DOIs\n"
     "%% are removed; the artifact is cited by its anonymous.4open.science copy (contribution 5 and the\n"
     "%% Open science appendix).\n", ""),
    ("\\documentclass[sigconf,review,anonymous]{acmart}", "\\documentclass[sigconf]{acmart}"),
    ("\\acmConference[ASIA CCS '27]{ACM ASIA Conference on Computer and\n  Communications Security}{July 12--16, 2027}{Macau, China}",
     "\\acmConference[Preprint]{Preprint}{November 2026}{Zenodo}"),
    # acmart's own pdfauthor comes out empty; the special sits on the title page so that it is always shipped
    ("\\maketitle\n", "\\maketitle\n\\special{pdf:docinfo<</Author (Vyom Kulshrestha)>>}\n"),
    ("%% Author block removed for double-blind review.\n\\author{Anonymous Author(s)}",
     "\\author{Vyom Kulshrestha}\n\\orcid{0009-0009-1434-7148}\n\\affiliation{%\n  \\institution{Independent Researcher}\n"
     "  \\country{India}}\n\\renewcommand{\\shortauthors}{Kulshrestha}"),
    ("\\item The registration, access ledger, harness and verifier, in the anonymized artifact at\n  \\url{" + ANON + "}.",
     "\\item The registration, access ledger, harness and verifier, in the public repository at\n  \\url{" + REPO + "}."),
    ("earlier registered studies on HAI [anonymized]", "earlier registered studies on HAI~\\cite{kulshrestha2026pinp}"),
    ("are available in the anonymized\nartifact at \\url{" + ANON + "}, which also contains",
     "are available in the public repository at\n\\url{" + REPO + "} (paper sources, results and verifier reports\n"
     "under \\texttt{docs/research}), which also contains"),
    ("% The de-anonymized repository and the artifact DOI are added in the camera-ready version.\n", ""),
    (" For review, the copy withholds the repository's commit history, which the\n"
     "verifiers use to check that every access followed its registration, and replaces the project name and\n"
     "commit hashes; its ANONYMIZATION.md lists each replacement.",
     " The repository's commit history shows that every registration was committed before\n"
     "the data access it governs."),
]
# The conference copies keep the generative-AI section (ACM and USENIX policy); the author's Zenodo
# preprints carry none, so the named version drops it.
AI_SECTION = "\\section*{Use of generative AI}"

BIB = """
@techreport{kulshrestha2026pinp,
  author      = {Kulshrestha, Vyom},
  title       = {Prediction Is Not Permission: Cross-Domain World Models Under Deterministic Runtime
                 Authority},
  institution = {Zenodo},
  type        = {Technical Report},
  number      = {version 1.3},
  year        = {2026},
  doi         = {10.5281/zenodo.23473173}
}
"""


def main():
    tex = (SRC / "main.tex").read_text(encoding="utf-8")
    for old, new in REPLACE:
        n = tex.count(old)
        if n != 1:
            raise SystemExit(f"expected one match, found {n}: {old[:80]!r}")
        tex = tex.replace(old, new)
    if tex.count(AI_SECTION) != 1:
        raise SystemExit(f"expected one {AI_SECTION}")
    start = tex.index(AI_SECTION)
    end = tex.index("\\end{document}", start)
    tex = tex[:start] + tex[end:]
    for bad in ("anonymous.4open", "[anonymized]", "Anonymous Author", "anonymous]{acmart}", "generative AI",
                "Claude"):
        if bad in tex:
            raise SystemExit(f"anonymous residue left: {bad}")
    if DST.exists():
        shutil.rmtree(DST)
    shutil.copytree(SRC / "figures", DST / "figures")
    for f in ("acmart.cls", "ACM-Reference-Format.bst"):
        shutil.copyfile(SRC / f, DST / f)
    (DST / "main.tex").write_text(tex, encoding="utf-8", newline="\n")
    bib = (SRC / "refs.bib").read_text(encoding="utf-8")
    (DST / "refs.bib").write_text(bib.rstrip("\n") + "\n" + BIB, encoding="utf-8", newline="\n")
    print("written", DST)


if __name__ == "__main__":
    main()
